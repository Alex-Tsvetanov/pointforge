// image_ops.hpp: стъпките на конвейера за откриване на контури.
//
// Редът е класическият: изглаждане с гаусово ядро, градиент по Собел,
// потискане на немаксимумите напречно на градиента, и двупрагово решение с
// проследяване на слабите отговори. Всяка стъпка е отделна функция с чист вход
// и изход, за да може да бъде проверена и измерена самостоятелно.
#ifndef POINTFORGE_IMAGE_OPS_HPP
#define POINTFORGE_IMAGE_OPS_HPP

#include <vector>

#include "pointforge/image.hpp"

namespace pointforge {

// Едномерно гаусово ядро с нечетна дължина, нормирано към сума 1.
// Радиусът е ceil(3 * sigma): извън него теглата падат под 1.2 % от върха и
// отрязването не се вижда при осем бита на канал.
std::vector<float> gaussian_kernel(float sigma);

// Разделимо изглаждане: първо по редове, после по стълбове. Цената е
// пропорционална на 2r вместо на (2r+1)^2 за същия резултат, което при
// sigma = 2 вече е около осемкратна разлика.
ImageF gaussian_blur(const ImageF& image, float sigma);

struct Gradient {
    ImageF gx;
    ImageF gy;
    ImageF magnitude;
};

// Градиент по Собел. Ядрата 3x3 също са разделими, на изглаждащо [1 2 1] и
// диференциращо [-1 0 1], и се прилагат в този вид.
Gradient sobel(const ImageF& image);

// Потискане на немаксимумите: пиксел оцелява само ако големината му е по-голяма
// от тази на двата си съседа по посоката на градиента. Посоката се закръгля до
// една от четири, а сравнението е със съседите в решетката, без интерполация,
// което е достатъчно за целочислен вход и е с една зависимост по-малко.
ImageF non_maximum_suppression(const Gradient& gradient);

// Двупрагово решение с проследяване: пикселите над high са контур, тези между
// low и high са контур само ако са свързани с вече приет контур. Изходът е
// двоичен, 0 или 255.
Image8 hysteresis_threshold(const ImageF& suppressed, float low, float high);

// Праг с една стойност. Ползва се за сегментацията, където входът е
// изображението, а не отговорът на детектора за контури.
Image8 threshold(const ImageF& image, float value, bool keep_above = true);

}  // namespace pointforge

#endif  // POINTFORGE_IMAGE_OPS_HPP
